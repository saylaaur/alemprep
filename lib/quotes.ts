/** Номер дня от эпохи для даты вида YYYY-MM-DD (UTC, без сдвига часового пояса). */
function dayNumber(date: string): number {
  return Math.floor(new Date(`${date}T00:00:00Z`).getTime() / 86_400_000);
}

/** Цитата дня: одна и та же весь день, меняется в полночь. */
export function dailyQuoteIndex(date: string, count: number = QUOTES.length): number {
  if (count <= 0) return 0;
  const n = dayNumber(date);
  if (!Number.isFinite(n)) return 0;
  return ((n % count) + count) % count;
}
