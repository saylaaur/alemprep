def _doublings(a: int, n: int) -> int:
    k, c = a, 0
    while k < n:
        k *= 2
        c += 1
    return c


EXPRS = [
    ("(A \\lor B) \\land \\lnot C", lambda A, B, C: (A or B) and not C),
    ("A \\land \\lnot B \\lor C", lambda A, B, C: (A and not B) or C),
    ("\\lnot (A \\land B) \\lor C", lambda A, B, C: (not (A and B)) or C),
    ("(A \\to B) \\land C", lambda A, B, C: ((not A) or B) and C),
    ("A \\lor B \\lor C", lambda A, B, C: A or B or C),
    ("A \\land B \\land \\lnot C", lambda A, B, C: A and B and not C),
    ("(A \\lor \\lnot B) \\land (B \\lor C)", lambda A, B, C: (A or not B) and (B or C)),
    ("\\lnot A \\land (B \\lor C)", lambda A, B, C: (not A) and (B or C)),
    ("(A \\to C) \\lor B", lambda A, B, C: ((not A) or C) or B),
    ("A \\equiv B", lambda A, B, C: A == B),
]


def _ones(f: int) -> int:
    fn = EXPRS[f][1]
    return sum(bool(fn(A, B, C)) for A in (False, True) for B in (False, True) for C in (False, True))


