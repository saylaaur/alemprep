def RUN(id_, topic, level, code, wrong, sol):
    """Вопрос «что выведет» — правильный ответ считается запуском кода при сборке."""
    PROGRAMS[id_] = code
    import contextlib
    import io

    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        exec(code, {})  # код наш, из этого файла
    out = buf.getvalue().strip().replace("\n", " ")
    return CODE(id_, topic, level, code, out, wrong, sol)


